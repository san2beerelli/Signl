/** Picks the right glyph for a device kind — reuses the icons above instead of inlining more SVG. */
export const DeviceKindIcon = ({ kind }: { kind: DeviceKind }): JSX.Element => {
  if (kind === "ios-simulator" || kind === "android-emulator") return <MonitorIcon size={18} />;
  if (kind === "browser-external") return <GlobeIcon size={18} />;
  return <SmartphoneIcon size={18} />;
};
